package com.kotsafe.security.p2p;

import java.nio.charset.StandardCharsets;
import java.security.GeneralSecurityException;
import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

/** Plain-JDK executable test: no Android SDK or main-project changes required. */
public final class TunnelPrimitivesTest {
    private static final String ROOM = "roomForTunnelTest_123456";
    private static final byte[] SECRET = "0123456789abcdef0123456789abcdef"
            .getBytes(StandardCharsets.UTF_8);

    @org.junit.Test
    public void testAllPrimitives() throws Exception {
        testCipherRoundTripAndReplayRejection();
        testInitialDataBuffer();
        testTransportSelection();
        testSecurePairingBundle();
        testGatewaySessionController();
        testExitExposurePolicy();
        testGatewayHealthVerificationAndKillSwitch();
        testDirectPunchCoordinatorWireProtocols();
    }

    public static void main(String[] args) throws Exception {
        new TunnelPrimitivesTest().testAllPrimitives();
        System.out.println("Android tunnel primitive tests passed");
    }

    private static void testCipherRoundTripAndReplayRejection() throws Exception {
        TunnelCipher client = new TunnelCipher(SECRET, ROOM);
        TunnelCipher exit = new TunnelCipher(SECRET, ROOM);
        String encrypted = client.seal("stream_12345678", TunnelCipher.CLIENT_TO_EXIT,
                "SOCKS greeting".getBytes(StandardCharsets.UTF_8));
        // Generated by the Node reference endpoint. This locks Android and
        // relay-reference implementations to the identical wire format.
        require(encrypted.equals("AAAAAAAAAAAiN-vGfcVqXCaJPYWSbqr1MNjnch9PVaiomprQg_c"),
                "cross-language encryption vector changed");
        require(!encrypted.contains("SOCKS"), "ciphertext must not contain plaintext");
        byte[] clear = exit.open("stream_12345678", TunnelCipher.CLIENT_TO_EXIT, encrypted);
        require(Arrays.equals(clear, "SOCKS greeting".getBytes(StandardCharsets.UTF_8)), "round trip failed");
        try {
            exit.open("stream_12345678", TunnelCipher.CLIENT_TO_EXIT, encrypted);
            throw new AssertionError("replayed frame was accepted");
        } catch (GeneralSecurityException expected) { }
    }

    private static void testInitialDataBuffer() throws Exception {
        List<String> sent = new ArrayList<>();
        BufferedTunnelStream stream = new BufferedTunnelStream(data -> sent.add(new String(data, StandardCharsets.UTF_8)));
        stream.write("first".getBytes(StandardCharsets.UTF_8));
        require(sent.isEmpty(), "initial data was sent before ready");
        stream.onReady();
        stream.write("second".getBytes(StandardCharsets.UTF_8));
        require(sent.equals(Arrays.asList("first", "second")), "buffer order was not retained");
    }

    private static void testTransportSelection() {
        require(TransportSelectionPolicy.choose(TransportSelectionPolicy.Mode.AUTOMATIC, true, true)
                == TransportSelectionPolicy.Path.DIRECT, "automatic must prefer direct");
        require(TransportSelectionPolicy.choose(TransportSelectionPolicy.Mode.AUTOMATIC, false, true)
                == TransportSelectionPolicy.Path.RELAY, "automatic must fall back to relay");
        require(TransportSelectionPolicy.choose(TransportSelectionPolicy.Mode.DIRECT_ONLY, false, true)
                == TransportSelectionPolicy.Path.BLOCKED, "direct-only must never silently relay");
        require(TransportSelectionPolicy.choose(TransportSelectionPolicy.Mode.RELAY_ONLY, true, true)
                == TransportSelectionPolicy.Path.RELAY, "relay-only must respect the user choice");
    }

    private static void testSecurePairingBundle() {
        SecurePairingBundle created = new SecurePairingBundle(
                "roomForGatewayPair_123456", "0123456789abcdef0123456789abcdef0123456789abcdef", "https://control.example.test");
        SecurePairingBundle parsed = SecurePairingBundle.parse(created.toQrUri());
        require(created.room.equals(parsed.room), "pairing room did not round trip");
        require(created.pairingSecret.equals(parsed.pairingSecret), "pairing secret did not round trip");
        try {
            new SecurePairingBundle(created.room, created.pairingSecret, "ftp://unsafe.example.test");
            throw new AssertionError("unsupported protocol control URL was accepted");
        } catch (IllegalArgumentException expected) { }
    }

    private static void testGatewaySessionController() {
        FakeConnector connector = new FakeConnector();
        final List<GatewaySessionController.State> states = new ArrayList<>();
        GatewaySessionController controller = new GatewaySessionController(connector, (state, detail) -> states.add(state));
        controller.start(TransportSelectionPolicy.Mode.AUTOMATIC, true);
        require(connector.direct != null, "automatic mode did not try direct first");
        connector.direct.complete(false, "carrier NAT");
        require(connector.relay != null, "automatic mode did not fall back to relay");
        connector.relay.complete(true, "relay connected");
        require(controller.getState() == GatewaySessionController.State.ACTIVE_RELAY, "relay did not become active");

        controller.start(TransportSelectionPolicy.Mode.DIRECT_ONLY, true);
        connector.direct.complete(false, "carrier NAT");
        require(controller.getState() == GatewaySessionController.State.BLOCKED, "direct-only leaked into a fallback path");
        require(states.contains(GatewaySessionController.State.CONNECTING_DIRECT), "direct status was not reported");
    }

    private static void testExitExposurePolicy() {
        ExitExposurePolicy.validate(ExitExposurePolicy.Listener.LOOPBACK_COMPATIBILITY, "127.0.0.1", true);
        ExitExposurePolicy.validate(ExitExposurePolicy.Listener.ENCRYPTED_TUNNEL_ONLY, null, true);
        try {
            ExitExposurePolicy.validate(ExitExposurePolicy.Listener.LOOPBACK_COMPATIBILITY, "0.0.0.0", true);
            throw new AssertionError("public raw SOCKS listener was accepted");
        } catch (IllegalArgumentException expected) { }
    }

    private static void testGatewayHealthVerificationAndKillSwitch() {
        GatewayHealthMonitor health = new GatewayHealthMonitor(true);
        health.onTunnelConnected(GatewayHealthMonitor.Path.DIRECT, 1_000L);
        require(health.shouldBlockProtectedTraffic(), "kill switch must block before exit verification");
        require(GatewayVpnRoutingPolicy.decide(true, health) == GatewayVpnRoutingPolicy.Decision.BLOCK,
                "routing policy allowed unverified gateway traffic");

        String nonce = health.beginEgressCheck(1_100L);
        require(!health.onEgressCheckResult("wrong", "203.0.113.7", 1_200L), "wrong nonce was accepted");
        require(health.onEgressCheckResult(nonce, "203.0.113.7", 1_200L), "valid egress check was rejected");
        health.onTunnelBytes(100L, 200L);
        GatewayHealthMonitor.Snapshot verified = health.snapshot();
        require(!health.shouldBlockProtectedTraffic(), "verified exit was still blocked");
        require(GatewayVpnRoutingPolicy.decide(true, health) == GatewayVpnRoutingPolicy.Decision.TUNNEL,
                "routing policy did not choose tunnel after verification");
        require(GatewayStatusFormatter.format(verified).contains("Exit IP verified: 203.0.113.7"),
                "status lacks verified IP");
        require(verified.sentBytes == 100L && verified.receivedBytes == 200L, "tunnel counters are wrong");

        require(health.tick(1_200L + GatewayHealthMonitor.HEARTBEAT_TIMEOUT_MS + 1L),
                "heartbeat loss was ignored");
        require(health.snapshot().status == GatewayHealthMonitor.Status.BLOCKED,
                "lost exit did not activate kill switch");

        GatewayHealthMonitor ipv6 = new GatewayHealthMonitor(false);
        ipv6.onTunnelConnected(GatewayHealthMonitor.Path.RELAY, 5_000L);
        String ipv6Nonce = ipv6.beginEgressCheck(5_100L);
        require(ipv6.onEgressCheckResult(ipv6Nonce, "2001:db8::7", 5_200L),
                "valid IPv6 egress result was rejected");
    }

    private static void testDirectPunchCoordinatorWireProtocols() {
        require(DirectPunchCoordinator.MAGIC == 0x50325044, "magic value mismatch");
        require(DirectPunchCoordinator.MSG_PUNCH_PING == 0x01, "ping opcode mismatch");
        require(DirectPunchCoordinator.MSG_PUNCH_PONG == 0x02, "pong opcode mismatch");
        require(DirectPunchCoordinator.MSG_DIRECT_DATA == 0x03, "data opcode mismatch");
        require(DirectPunchCoordinator.MSG_DIRECT_ACK == 0x04, "ack opcode mismatch");
        require(DirectPunchCoordinator.MSG_HEARTBEAT == 0x05, "heartbeat opcode mismatch");
    }

    private static final class FakeConnector implements GatewaySessionController.Connector {
        GatewaySessionController.AttemptCallback direct;
        GatewaySessionController.AttemptCallback relay;
        @Override public void connectDirect(GatewaySessionController.AttemptCallback callback) { direct = callback; }
        @Override public void connectRelay(GatewaySessionController.AttemptCallback callback) { relay = callback; }
        @Override public void stop() { direct = null; relay = null; }
    }

    private static void require(boolean condition, String message) {
        if (!condition) throw new AssertionError(message);
    }
}
